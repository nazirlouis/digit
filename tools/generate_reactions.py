"""Validate Digit's authored reactions and emit identical C++/MicroPython timelines.

Run normally to regenerate, or --check in tests to reject stale generated files.
This tool never opens a serial port or accesses a controller.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reactions/digit_reactions.json"
ORDER = ("neutral", "happy", "sad", "mad", "serious", "curious", "surprised",
         "sleeping", "confused", "sleepy", "excited", "crying", "love")
PROFILES = ("expression", "gesture", "wake")
KINDS = ("whistle", "chatter", "rasp")


def validate(data):
    def require(condition, message):
        if not condition:
            raise ValueError(message)

    require(data.get("schema_version") == 1, "unsupported schema version")
    require(data.get("sample_rate") == 16000, "expected 16 kHz reference rate")
    require(tuple(data.get("face_order", ())) == ORDER, "face order must match AudioCue")
    entries = data.get("reactions", [])
    require(tuple(item["name"] for item in entries) == ORDER, "need exactly 13 ordered reactions")
    for entry in entries:
        require(set(entry["profiles"]) == set(PROFILES), "each face needs all profiles")
        for kind in PROFILES:
            profile = entry["profiles"][kind]
            label = entry["name"] + "." + kind
            require(isinstance(profile.get("gain"), (int, float)) and 0 < profile["gain"] <= 1,
                    label + ": profile gain must reduce, never boost")
            for field in ("enter_ms", "exit_ms", "voice_ms", "lead_ms"):
                require(type(profile[field]) is int and 0 <= profile[field] <= 6000,
                        label + ": invalid " + field)
            hold = profile["hold_ms"]
            persistent = hold is None
            require(persistent == (kind == "expression" and entry["name"] in ("neutral", "sleeping")),
                    label + ": invalid persistent face")
            if not persistent:
                require(type(hold) is int and 0 <= hold <= 6000, label + ": invalid hold")
                require(profile["enter_ms"] + hold + profile["exit_ms"] == profile["voice_ms"],
                        label + ": voice and face timelines must end together")
            notes = profile["notes"]
            require(1 <= len(notes) <= 8, label + ": invalid note count")
            elapsed = profile["lead_ms"]
            for note in notes:
                require(type(note["ms"]) is int and 20 <= note["ms"] <= 2000,
                        label + ": invalid note duration")
                require(type(note["gap_ms"]) is int and 0 <= note["gap_ms"] <= 1000,
                        label + ": invalid gap")
                require(2 <= len(note["hz"]) <= 4 and all(type(hz) is int and 180 <= hz <= 1900 for hz in note["hz"]),
                        label + ": invalid contour frequency")
                require(note["kind"] in KINDS, label + ": invalid tone kind")
                require(0 < note["level"] <= .8 and 0 <= note["warble"] <= .15,
                        label + ": invalid amplitude/warble")
                elapsed += note["ms"] + note["gap_ms"]
            require(elapsed + 25 <= profile["voice_ms"], label + ": no quiet settling tail")
            if kind == "wake":
                require(profile["voice_ms"] <= 900, "wake must finish within 900 ms")
    return entries


def cpp_float(value):
    result = format(value, ".6g")
    if "." not in result:
        result += ".0"
    return result + "f"


def render_cpp(entries, version):
    lines = ["// Generated by tools/generate_reactions.py. Edit reactions/digit_reactions.json.",
             "#pragma once", "#include <cstdint>", "namespace reaction_catalog {",
             "inline constexpr uint32_t version = 0x" + version + "U;",
             "struct Timing { uint16_t enterMs, holdMs, exitMs, voiceMs, leadMs; bool persistent; };",
             "enum class Tone : uint8_t { Whistle, Chatter, Rasp };",
             "struct Note { uint16_t ms, gapMs, hz[4]; uint8_t points; Tone tone; float level, warble; };",
             "struct Phrase { uint8_t count; float gain; Note notes[8]; };",
             "inline constexpr const char* names[13] = {" + ",".join('"' + name.upper() + '"' for name in ORDER) + "};"]
    for kind in PROFILES:
        lines.append("inline constexpr Timing " + kind + "[13] = {")
        for entry in entries:
            p = entry["profiles"][kind]
            fields = [p["enter_ms"], p["hold_ms"] or 0, p["exit_ms"], p["voice_ms"], p["lead_ms"]]
            lines.append("  {" + ",".join(map(str, fields)) + "," + str(p["hold_ms"] is None).lower() + "}, // " + entry["name"])
        lines.append("};")
        lines.append("inline constexpr Phrase " + kind + "Phrases[13] = {")
        for entry in entries:
            notes = entry["profiles"][kind]["notes"]
            gain = entry["profiles"][kind]["gain"]
            lines.append("  {" + str(len(notes)) + ", " + cpp_float(gain) + ", {")
            for note in notes:
                points = note["hz"] + [0] * (4 - len(note["hz"]))
                lines.append("    {" + str(note["ms"]) + "," + str(note["gap_ms"]) + ",{" +
                             ",".join(map(str, points)) + "}," + str(len(note["hz"])) + ",Tone::" +
                             note["kind"].title() + "," + cpp_float(note["level"]) + "," +
                             cpp_float(note["warble"]) + "},")
            lines.append("  }}, // " + entry["name"])
        lines.append("};")
    lines.append("} // namespace reaction_catalog")
    return "\n".join(lines) + "\n"


def render_python(entries, version):
    lines = ['"""Generated by tools/generate_reactions.py; edit reactions/digit_reactions.json."""',
             "CATALOG_VERSION = 0x" + version, "TIMINGS = {"]
    for entry in entries:
        p = entry["profiles"]["expression"]
        lines.append("    " + repr(entry["name"]) + ": " + repr((p["enter_ms"], p["hold_ms"], p["exit_ms"])) + ",")
    wake = entries[1]["profiles"]["wake"]
    lines += ["}", "WAKE_TIMING = " + repr((wake["enter_ms"], wake["hold_ms"], wake["exit_ms"]))]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    entries = validate(data)
    canonical = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    version = hashlib.sha256(canonical).hexdigest()[:8]
    outputs = {ROOT / "xiao-sense/src/reaction_catalog.h": render_cpp(entries, version),
               ROOT / "zumo-controller/reaction_catalog.py": render_python(entries, version)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit("Generated reaction catalog is stale: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print("PASS: 13 authored faces, exact native phrases, shared timelines" + (" (generated files current)" if args.check else " (generated)"))


if __name__ == "__main__":
    main()
